export function translateUiText(source, locale) {
  if (locale !== "zh-CN" || typeof source !== "string") return source;
  const normalizedSource = source.replace(/\s+/gu, " ").trim();
  const exact = ZH_CN[normalizedSource];
  if (exact) return exact;
  const patterns = [
    [/^Connects to (.+)\. The token is exchanged for a secure browser session and is never stored by the page\.$/u,
      (_match, destination) => `用于连接 ${destination}。token 会被交换为安全的浏览器会话，且不会被页面存储。`],
    [/^(\d+) member(s?) · (owner|participant|viewer)$/u, (_match, count, plural, role) => `${count} 位成员 · ${ZH_CN[role] ?? role}`],
    [/^Contiguous through sequence #(\d+)$/u, (_match, sequence) => `连续历史已到 sequence #${sequence}`],
    [/^Live · #(\d+)$/u, (_match, sequence) => `实时 · #${sequence}`],
    [/^Read only · #(\d+)$/u, (_match, sequence) => `只读 · #${sequence}`],
    [/^You are (owner|participant|viewer)$/u, (_match, role) => `你的角色是 ${ZH_CN[role] ?? role}`],
    [/^(.+) · You are (owner|participant|viewer)$/u, (_match, description, role) => `${translateUiText(description, "zh-CN")} · 你的角色是 ${ZH_CN[role] ?? role}`],
    [/^Role for (.+)$/u, (_match, name) => `${name} 的角色`],
    [/^Delete the cloud session “(.+)”\?$/u, (_match, name) => `删除云端会话“${name}”？`],
    [/^Delete the cloud project “(.+)” and all of its cloud sessions\?$/u, (_match, name) => `删除云端项目“${name}”及其全部云端会话？`],
    [/^Configured projection ceiling: (.+) \(about ([\d,]+) tokens at four UTF-8 bytes per token\)\. The connected model's reported window remains the hard upper bound\. Reconnect Codex after changing this value\. Desktop Hook updates use a separate 7 KiB capsule and continue across turns\.$/u,
      (_match, bytes, tokens) => `配置的投影上限：${bytes}（按每 token 四个 UTF-8 字节估算约 ${tokens} tokens）。接入模型实际报告的上下文窗口仍是硬上限；更改此值后请重新连接 Codex。Desktop Hooks（钩子）更新使用独立的 7 KiB 胶囊，并会在后续 turns 中持续补充。`],
  ];
  for (const [pattern, render] of patterns) {
    const match = normalizedSource.match(pattern);
    if (match) return render(...match);
  }
  return source;
}

