export function createLocalizer(documentObject = globalThis.document) {
  const textState = new WeakMap();
  const attributeState = new WeakMap();
  let locale = "en";
  let observer;

  const isSkipped = (node) => node.parentElement?.closest(SKIP_SELECTOR) != null;
  const translateTextNode = (node) => {
    if (isSkipped(node)) return;
    const current = node.nodeValue ?? "";
    const trimmed = current.trim();
    if (!trimmed) return;
    const prior = textState.get(node);
    const source = prior && trimmed === prior.rendered ? prior.source : trimmed;
    const rendered = translateUiText(source, locale);
    textState.set(node, { source, rendered });
    if (rendered !== trimmed) node.nodeValue = current.replace(trimmed, rendered);
  };
  const translateElementAttributes = (node) => {
    if (node.matches?.(SKIP_SELECTOR)) return;
    let state = attributeState.get(node);
    if (!state) {
      state = new Map();
      attributeState.set(node, state);
    }
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      const current = node.getAttribute?.(attribute);
      if (!current) continue;
      const prior = state.get(attribute);
      const source = prior && current === prior.rendered ? prior.source : current;
      const rendered = translateUiText(source, locale);
      state.set(attribute, { source, rendered });
      if (current !== rendered) node.setAttribute(attribute, rendered);
    }
  };
  const translateSubtree = (root) => {
    if (!root) return;
    if (root.nodeType === 3) translateTextNode(root);
    if (root.nodeType === 1) translateElementAttributes(root);
    const whatToShow = (globalThis.NodeFilter?.SHOW_ELEMENT ?? 1) | (globalThis.NodeFilter?.SHOW_TEXT ?? 4);
    const walker = documentObject.createTreeWalker(root, whatToShow);
    let node = walker.nextNode();
    while (node) {
      if (node.nodeType === 3) translateTextNode(node);
      else translateElementAttributes(node);
      node = walker.nextNode();
    }
  };
  observer = new MutationObserver((mutations) => {
    if (locale !== "zh-CN") return;
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTextNode(mutation.target);
      for (const node of mutation.addedNodes ?? []) translateSubtree(node);
      if (mutation.type === "attributes") translateElementAttributes(mutation.target);
    }
  });
  observer.observe(documentObject.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["aria-label", "placeholder", "title"] });
  return {
    apply(nextLocale) {
      locale = nextLocale === "zh-CN" ? "zh-CN" : "en";
      documentObject.documentElement.lang = locale;
      translateSubtree(documentObject.body);
    },
    t(source) {
      return translateUiText(source, locale);
    },
    dispose() {
      observer.disconnect();
    },
  };
}
