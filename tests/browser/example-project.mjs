// Only authored, isolated examples. No account, runtime or provider is used.
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium, webkit } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(resolve(process.env.PLAYWRIGHT_MODULE)).href : 'playwright');
const origin = process.env.ONBOARDING_ORIGIN ?? 'http://127.0.0.1:4173';
const artifacts = process.env.ONBOARDING_ARTIFACTS ?? '/tmp/gatherthread-example-project';
await mkdir(artifacts, { recursive: true });
const name = process.env.ONBOARDING_BROWSER ?? 'chromium';
const browser = await (name === 'webkit' ? webkit.launch() : chromium.launch(
  process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH ? { executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH } : {}));
try {
  for (const locale of ['en', 'zh-CN']) for (const [width, height] of [[1440, 900], [390, 844], [320, 568], [820, 1180]]) {
    const context = await browser.newContext({ viewport: { width, height }, reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [], remote = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => { if (!request.url().startsWith(origin) && !request.url().startsWith('data:')) remote.push(request.url()); });
    await page.goto(`${origin}/app/example.html?locale=${locale}&topic=browse&layout=${width <= 820 ? 'mobile' : 'desktop'}`);
    await page.locator('#session-view:not([hidden])').waitFor();
    await page.locator('#example-project-open').click();
    const dialog = page.locator('#example-project-dialog[open]');
    await dialog.waitFor();
    await page.locator('#example-project-frame[aria-busy="false"]').waitFor();
    const preview = page.frameLocator('#example-project-frame');
    await preview.locator('#signup').click();
    await preview.locator('#signup:disabled').waitFor();
    assert.equal(await preview.locator('#signup').isDisabled(), true);
    assert.equal(await preview.locator('#confirmation').innerText(), locale === 'zh-CN' ? '报名成功。' : 'You’re signed up.');
    await page.locator('#example-project-version').selectOption('branch-maya');
    await page.locator('#example-project-frame[aria-busy="false"]').waitFor();
    await preview.locator('#signup:not([disabled])').waitFor();
    await preview.locator('#signup').click();
    assert.match(await preview.locator('#confirmation').innerText(), locale === 'zh-CN' ? /周六见/ : /See you Saturday/);
    const isolated = await preview.locator('body').evaluate(() => { try { void parent.document.body; return false; } catch { return true; } });
    assert.equal(isolated, true, 'executed demo cannot read the application');
    await page.screenshot({ path: `${artifacts}/${name}-${locale}-${width}-result.png` });
    await page.locator('#example-files-tab').click();
    await dialog.waitFor({ state: 'hidden' });
    const workspace = page.locator('.file-workspace');
    await workspace.waitFor();
    assert.equal(await page.locator('#example-file-list, #example-source-code').count(), 0, 'demo source has no duplicate viewer');
    await page.locator('.fw-branch-select').selectOption('branch-maya');
    await page.locator('.fw-tree [data-path="src"]').click();
    await page.locator('.fw-tree [data-path="src/signup.js"]').click();
    const source = page.locator('.fw-file-pane .cm-content');
    await source.waitFor();
    assert.match(await source.innerText(), /addEventListener/);
    assert.match(await source.innerText(), locale === 'zh-CN' ? /周六见/ : /See you Saturday/);
    assert.equal(await source.getAttribute('contenteditable'), 'false', 'teammate source is read-only');
    await page.screenshot({ path: `${artifacts}/${name}-${locale}-${width}-code.png` });
    await workspace.locator('[data-tab="files"]').click();
    await workspace.locator('[data-explorer-view="changes"]').click();
    await workspace.locator('.fw-change').filter({ hasText: 'src/signup.js' }).click();
    await workspace.locator('.cm-mergeView').waitFor();
    assert.ok(await workspace.locator('.cm-changedLine').count() > 0, 'real editor marks saved branch changes');
    await workspace.locator('[data-tab="files"]').click();
    await workspace.locator('.fw-branch-select').selectOption('branch-example');
    await workspace.locator('.fw-tree [data-path="src"]').click();
    await workspace.locator('.fw-tree [data-path="src/signup.js"]').click();
    await source.waitFor();
    assert.equal(await source.getAttribute('contenteditable'), 'true', 'own source is editable');
    const tabsBeforeReadme = await workspace.locator('.fw-tabs [role="tab"]').count();
    await workspace.locator('[data-tab="files"]').click();
    await workspace.locator('.fw-tree [data-path="README.md"]').click();
    await workspace.locator('.fw-markdown h1').waitFor();
    assert.equal(await workspace.locator('.fw-tabs [role="tab"]').count(), tabsBeforeReadme + 1, 'source tabs share the real workspace');
    await workspace.getByRole('button', { name: locale === 'zh-CN' ? '代码' : 'Code', exact: true }).click();
    await source.waitFor();
    assert.match(await source.innerText(), /^#/);
    await workspace.getByRole('button', { name: locale === 'zh-CN' ? '预览' : 'Preview', exact: true }).click();
    await workspace.locator('.fw-markdown h1').waitFor();
    await workspace.locator('.fw-tab-dismiss').last().click();
    assert.equal(await workspace.locator('.fw-tabs [role="tab"]').count(), tabsBeforeReadme, 'file tabs close independently');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if (width <= 820) { await workspace.locator('.fw-tabs-list').click(); await workspace.locator('.fw-collapse-command').click(); }
    else await page.locator('#open-files-button').click();
    await page.locator('#example-project-open').click();
    await page.locator('#example-project-version').selectOption('main');
    await page.locator('#example-project-frame[aria-busy="false"]').waitFor();
    await preview.locator('#signup').waitFor();
    assert.equal(await preview.locator('#confirmation').isVisible(), false, 'reopening resets the executed page');
    await page.keyboard.press('Escape');
    assert.equal(await dialog.count(), 0);
    assert.deepEqual(errors, []);
    assert.deepEqual(remote, [], 'no external model, image, font or account access');
    console.log(`${name}: ${locale} ${width}x${height} source, result, version and isolation passed`);
    await context.close();
  }
} finally { await browser.close(); }
